#!/usr/bin/env python3
"""Claude B: everything that is left for the voice side, in one command. Each step is independent: a failed step is recorded and the rest continue.

    python scripts/b_finish_all.py [--kokoro K.onnx --voices V.bin]

Steps (run AFTER scripts/b_run_all.py has produced out/ and data/subsets/):
  1 length sweep           first 0.1 ... 6 s of the held-out eval clips             -> out/B_LENGTH_SWEEP.md
  2 speech-to-text sample  faster-whisper on a few clips (downloads the model once) -> out/B_STT_SAMPLE.json
  3 Hinglish set           builds labels, scores data/hinglish/{real,fake} if clips exist -> out/B_HINGLISH.md
  4 In-the-Wild probe      lists the files and sizes on Hugging Face, downloads NOTHING   -> out/B_ITW_PROBE.txt
  5 report + bundle        out/B_FINISH_REPORT.md and out/veriq_B_final_bundle.zip (send this to Claude C)
Not automated, and why: MLAAD (no Hindi, gated, non-commercial) and SEA-Spoof (licence unstated): see HANDOFF_B_FINAL.md.
"""
from __future__ import annotations

import argparse
import csv
import json
import os
import shutil
import statistics
import subprocess
import sys
import zipfile
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PY = sys.executable
OUT = ROOT / "out"
CAL = OUT / "calibration_asvspoof_dev.json"
sys.path.insert(0, str(ROOT / "scripts"))
REPORT: list = []


def sh(cmd, timeout=3600, env=None):
    p = subprocess.run([str(c) for c in cmd], cwd=ROOT, capture_output=True, text=True, timeout=timeout, env=env)
    return p.returncode, (p.stdout + p.stderr)


def step(name):
    def deco(fn):
        def run(*a, **k):
            print(f"[{name}] ...", flush=True)
            try:
                status, note = fn(*a, **k)
            except Exception as e:  # a failed step never stops the others
                status, note = "FAIL", f"{type(e).__name__}: {e}"[:300]
            REPORT.append((name, status, note))
            print(f"[{name}] {status} {note}", flush=True)
        return run
    return deco


@step("1 length sweep")
def s_length(env):
    if not (ROOT / "data" / "subsets" / "eval" / "labels.csv").is_file():
        return "SKIP", "run scripts/b_run_all.py first"
    rc, out = sh([PY, "scripts/length_sweep.py", "--calibration", CAL], env=env)
    return ("PASS", "out/B_LENGTH_SWEEP.md") if rc == 0 else ("FAIL", out.strip()[-300:])


@step("2 speech-to-text sample")
def s_stt(env):
    clips = sorted((ROOT / "data" / "subsets" / "eval" / "real").glob("*__opus.wav"))[:2]
    clips += sorted((ROOT / "data" / "hinglish" / "real").glob("*"))[:3]
    clips += sorted((ROOT / "data" / "hinglish" / "fake").glob("*"))[:1]
    if not clips:
        return "SKIP", "no clips found"
    res = []
    for c in clips:
        rc, out = sh([PY, "-m", "voice.transcribe", c], timeout=900, env=env)
        try:
            d = json.loads(out[out.index("{"):])
        except ValueError:
            d = {"error": out.strip()[-200:]}
        d["clip"] = str(c.relative_to(ROOT).as_posix())
        res.append(d)
    (OUT / "B_STT_SAMPLE.json").write_text(json.dumps(res, indent=2, ensure_ascii=False), encoding="utf-8")
    ok = sum(1 for d in res if d.get("text"))
    return ("PASS" if ok else "FAIL"), f"{ok}/{len(res)} clips transcribed -> out/B_STT_SAMPLE.json (first run downloads the model)"


@step("3 Hinglish set")
def s_hinglish(env):
    base = ROOT / "data" / "hinglish"
    if not any((base / k).is_dir() and any((base / k).iterdir()) for k in ("real", "fake")):
        return "SKIP", "no clips yet: run scripts/hinglish_build.py prompts / fakes, record the real clips, then re-run"
    rc, o = sh([PY, "scripts/hinglish_build.py", "labels"])
    if rc != 0:
        return "FAIL", o.strip()[-200:]
    cmd = [PY, "-m", "eval", "--input", base, "--out", OUT / "hinglish.csv", "--labels", base / "labels.csv"]
    if CAL.is_file():
        cmd += ["--calibration", CAL]
    rc, o = sh(cmd, env=env)
    if rc != 0:
        return "FAIL", o.strip()[-300:]
    from make_results_rows import block, fmt
    rows = list(csv.DictReader(open(OUT / "hinglish.csv", newline="", encoding="utf-8")))
    b = block(rows)
    ci = lambda t: f"[{fmt(t[0])}, {fmt(t[1])}]"
    md = ["## Hinglish own set (tiny; real = teammates with consent, fake = Kokoro TTS generated by us)", "",
          "| n | AUC | EER | genuine flagged (95% Wilson) | synthetic missed (95% Wilson) | abstained |", "|---|---|---|---|---|---|",
          f"| {b['n']} (real {b['n_real']}, fake {b['n_fake']}) | {fmt(b['auc'])} | {fmt(b['eer'])} | {fmt(b['fa'])} {ci(b['fa_ci'])} | "
          f"{fmt(b['miss'])} {ci(b['miss_ci'])} | {b['abstained']} |", "",
          "Dev-fitted ASVspoof threshold (not tuned here). Few speakers and one TTS engine: this shows behaviour, not accuracy. Same sentences for real and fake."]
    (OUT / "B_HINGLISH.md").write_text("\n".join(md), encoding="utf-8")
    return "PASS", f"n={b['n']} -> out/B_HINGLISH.md"


@step("4 In-the-Wild probe")
def s_itw(env):
    try:
        from huggingface_hub import HfApi
    except ImportError:
        return "SKIP", "pip install huggingface_hub to probe"
    files = [f for f in HfApi().list_repo_tree("mueller91/In-The-Wild", repo_type="dataset", recursive=True) if hasattr(f, "size")]
    tot = sum((f.size or 0) for f in files)
    names = [f.path for f in files]
    meta = [n for n in names if n.lower().endswith((".csv", ".json", ".txt", ".md", ".parquet"))]
    txt = [f"mueller91/In-The-Wild: {len(files)} files, {tot / 1e9:.2f} GB total", "metadata-like files: " + ", ".join(meta[:20]),
           "first files: " + ", ".join(names[:10]),
           "Nothing downloaded. Licence on the HF card: CC-BY-SA-4.0 (the demo page says Apache-2.0: they disagree, verify). Test only, never fit."]
    (OUT / "B_ITW_PROBE.txt").write_text("\n".join(txt), encoding="utf-8")
    return "PASS", f"{len(files)} files, {tot / 1e9:.2f} GB -> out/B_ITW_PROBE.txt"


def finish() -> None:
    lines = [f"# B_FINISH_REPORT ({datetime.now():%Y-%m-%d %H:%M} local)", "", "| step | status | note |", "|---|---|---|"]
    lines += [f"| {n} | {s} | {t.replace(chr(10), ' ')[:200]} |" for n, s, t in REPORT]
    (OUT / "B_FINISH_REPORT.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    pub = ROOT / "results" / "asvspoof"
    pub.mkdir(parents=True, exist_ok=True)
    for f in ("B_FINISH_REPORT.md", "B_LENGTH_SWEEP.md", "B_STT_SAMPLE.json", "B_HINGLISH.md", "B_ITW_PROBE.txt"):
        if (OUT / f).is_file():
            shutil.copy(OUT / f, pub / f)
    for p in OUT.glob("hinglish.csv"):
        with open(p, newline="", encoding="utf-8") as fh:
            rd = csv.DictReader(fh)
            keep = [c for c in rd.fieldnames if c != "path"]
            rows = [{c: r[c] for c in keep} for r in rd]
        with open(pub / p.name, "w", newline="", encoding="utf-8") as fh:
            w = csv.DictWriter(fh, fieldnames=keep)
            w.writeheader()
            w.writerows(rows)
    bundle = OUT / "veriq_B_final_bundle.zip"
    with zipfile.ZipFile(bundle, "w", zipfile.ZIP_DEFLATED) as z:
        for base in (ROOT / "data" / "subsets" / "eval_len", ROOT / "data" / "hinglish", OUT):
            for p in sorted(base.rglob("*")) if base.is_dir() else []:
                if p.is_file() and p.suffix != ".zip" and ".tmp" not in p.parts:
                    z.write(p, p.relative_to(ROOT).as_posix())
    print(f"[bundle] {bundle} ({bundle.stat().st_size / 1e6:.1f} MB)")
    print("\n".join(lines))


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--aasist-repo", default=os.environ.get("VERIQ_AASIST_REPO", str(ROOT / "external" / "aasist")))
    a = ap.parse_args(argv)
    OUT.mkdir(exist_ok=True)
    env = dict(os.environ, VERIQ_AASIST_REPO=a.aasist_repo)
    s_length(env)
    s_stt(env)
    s_hinglish(env)
    s_itw(env)
    finish()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
