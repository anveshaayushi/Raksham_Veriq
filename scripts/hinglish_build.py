#!/usr/bin/env python3
"""Own Hindi/Hinglish test set (tiny, consented, synthetic-plus-own-voice). Same 12 sentences for real and fake, so the words do not give the label away.

  python scripts/hinglish_build.py prompts                       # writes data/hinglish/PROMPTS.md (teammates read these aloud)
  python scripts/hinglish_build.py fakes --kokoro <kokoro-v1.0.onnx> --voices <voices-v1.0.bin>   # TTS fakes (Apache-2.0 Kokoro, 4 Hindi voices)
  python scripts/hinglish_build.py labels                        # scans data/hinglish/real and /fake, writes labels.csv

REAL clips: each teammate records the 12 sentences (phone voice note or Windows Voice Recorder, any of .opus .m4a .wav .mp3)
and saves them as data/hinglish/real/<name>_<01..12>.<ext>. Everyone must consent to their voice being used for this test.
Synthetic = generated by us; generation code is this file (organisers' rule 1). All sentences are invented; no real person or firm.
LIMITS: ~36 real + ~48 fake clips from 3 voices and one TTS engine: it shows behaviour on Hinglish, it is NOT an accuracy benchmark.
"""
from __future__ import annotations

import argparse
import csv
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BASE = ROOT / "data" / "hinglish"
AUDIO = {".wav", ".opus", ".ogg", ".m4a", ".mp3", ".flac", ".aac", ".amr", ".webm", ".mp4"}
HI_VOICES = ["hf_alpha", "hf_beta", "hm_omega", "hm_psi"]
# (Devanagari used for TTS and reading, romanised for readers who prefer it, kind of sentence)
SENTENCES = [
    ("नमस्ते, मैं निवेश सलाहकार बोल रहा हूँ। आज ही पैसे ट्रांसफर कर दीजिए।", "Namaste, main nivesh salahkar bol raha hoon. Aaj hi paise transfer kar dijiye.", "pressure"),
    ("यह ऑफर सिर्फ आज के लिए है, देर मत कीजिए।", "Yeh offer sirf aaj ke liye hai, der mat kijiye.", "pressure"),
    ("मैंने आपको यूपीआई आईडी भेजी है, पाँच हज़ार रुपये अभी भेजिए।", "Maine aapko UPI ID bheji hai, paanch hazaar rupaye abhi bhejiye.", "pressure"),
    ("गारंटीड रिटर्न मिलेगा, बस आज रजिस्ट्रेशन फीस जमा कीजिए।", "Guaranteed return milega, bas aaj registration fees jama kijiye.", "pressure"),
    ("आपका खाता बंद होने वाला है, तुरंत ओटीपी बताइए।", "Aapka khata band hone wala hai, turant OTP bataiye.", "pressure"),
    ("भैया, कल की मीटिंग शाम पाँच बजे है, ठीक से पहुँच जाना।", "Bhaiya, kal ki meeting shaam paanch baje hai, theek se pahunch jaana.", "ordinary"),
    ("मम्मी, मैंने किराए के पैसे भेज दिए हैं, देख लेना।", "Mummy, maine kiraye ke paise bhej diye hain, dekh lena.", "ordinary"),
    ("आज सब्ज़ी लेते आना, और दूध भी।", "Aaj sabzi lete aana, aur doodh bhi.", "ordinary"),
    ("रिपोर्ट मैंने ईमेल कर दी है, कृपया देख लीजिए।", "Report maine email kar di hai, kripya dekh lijiye.", "ordinary"),
    ("आपका स्टेटमेंट तैयार है, बैंक की शाखा से ले लीजिए।", "Aapka statement taiyaar hai, bank ki shakha se le lijiye.", "ordinary"),
    ("कल बारिश हो सकती है, छाता साथ रखना।", "Kal baarish ho sakti hai, chhata saath rakhna.", "ordinary"),
    ("निवेश से पहले सेबी रजिस्ट्रेशन ज़रूर जाँच लीजिए।", "Nivesh se pehle SEBI registration zaroor jaanch lijiye.", "ordinary"),
]


def cmd_prompts(a) -> int:
    BASE.mkdir(parents=True, exist_ok=True)
    lines = ["# Hinglish recording prompts", "",
             "Read each sentence aloud once, in your normal voice, at normal speed. Record as a phone voice note or Windows Voice Recorder.",
             "Save as `data\\hinglish\\real\\<yourname>_01` ... `_12` (any of .opus .m4a .wav .mp3). Quiet room, phone about 20 cm away.",
             "By recording you consent to the clips being used for this test set and shared with the team. Do not say any real name or number.", ""]
    for i, (dev, rom, kind) in enumerate(SENTENCES, 1):
        lines += [f"{i:02d}. {dev}", f"    {rom}", ""]
    (BASE / "PROMPTS.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {BASE / 'PROMPTS.md'}")
    return 0


def _ffmpeg(src: Path, dst: Path) -> None:
    dst.parent.mkdir(parents=True, exist_ok=True)
    subprocess.run(["ffmpeg", "-nostdin", "-y", "-loglevel", "error", "-i", str(src), "-ac", "1", "-ar", "16000", str(dst)],
                   check=True, capture_output=True, timeout=60)


def cmd_fakes(a) -> int:
    try:
        import soundfile as sf
        from kokoro_onnx import Kokoro
    except ImportError as e:
        print(f"need: pip install kokoro-onnx soundfile  ({e})", file=sys.stderr)
        return 2
    k = Kokoro(a.kokoro, a.voices)
    n = 0
    for v in HI_VOICES:
        for i, (dev, _rom, _k) in enumerate(SENTENCES, 1):
            x, sr = k.create(dev, voice=v, speed=1.0, lang="hi")
            with tempfile.TemporaryDirectory() as d:
                raw = Path(d) / "a.wav"
                sf.write(str(raw), x, sr)
                _ffmpeg(raw, BASE / "fake" / f"{v}_{i:02d}.wav")
            n += 1
    print(f"wrote {n} synthetic Hindi clips to {BASE / 'fake'} (Kokoro-82M, Apache-2.0; generated by us)")
    return 0


def cmd_labels(a) -> int:
    rows = []
    for lab in ("real", "fake"):
        for p in sorted((BASE / lab).glob("*")) if (BASE / lab).is_dir() else []:
            if p.suffix.lower() in AUDIO:
                rows.append((f"{lab}/{p.name}", lab, "hinglish_own", "original" if lab == "real" else "tts_clean", "hi"))
    if not rows:
        print("no clips found under data/hinglish/real or /fake", file=sys.stderr)
        return 1
    with open(BASE / "labels.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["file", "label", "dataset", "codec", "language"])
        w.writerows(rows)
    nr = sum(r[1] == "real" for r in rows)
    print(f"labels.csv: {nr} real, {len(rows) - nr} fake")
    return 0


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("prompts")
    f = sub.add_parser("fakes")
    f.add_argument("--kokoro", required=True)
    f.add_argument("--voices", required=True)
    sub.add_parser("labels")
    a = ap.parse_args(argv)
    return {"prompts": cmd_prompts, "fakes": cmd_fakes, "labels": cmd_labels}[a.cmd](a)


if __name__ == "__main__":
    raise SystemExit(main())
