def targets() -> list[dict]:
    """The deck's four 'AT THE FINALE · TARGETS, NOT RESULTS' (p8), with what we measured."""
    def load(rel):
        p = ROOT / rel
        try:
            return json.loads(p.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            return None
    test, blind, timing = load("bench/results_test.json"), load("results/q2/blind.json"), load("results/timing_chat_with_voice.json")
    out = []
    fa = test and test["false_alarms_on_legit_payees"]
    blind_fa = blind and blind["genuine_false_alarm"]
    out.append({"target": "False mismatch, 30 held-out legitimate chats: 0",
                "measured": (f"held-out synthetic test (generated by us): {fa['count']} false alarms on {fa['of']} genuine payees "
                             f"(~100 genuine chats; generated by us)" if fa else "not run")
                + ("; blind teammate set: " + (f"{blind_fa['count']}/{blind_fa['of']} genuine chats" if blind_fa else "not run")),
                "status": "measured (synthetic); blind: " + ("measured" if blind_fa else "not run")})
    ex = test and test["extraction"]
    out.append({"target": "Payee extraction precision >= 0.98",
                "measured": f"{ex['precision']} ({ex['tp']} found, {ex['fp']} false pickups; synthetic)" if ex else "not run",
                "status": "met on synthetic data" if ex and ex["precision"] >= 0.98 else "not run"})
    out.append({"target": "Time per chat with voice notes <= 60 s",
                "measured": (f"{timing['seconds']} s for a {timing['messages']}-message chat with {timing['voice_notes']} "
                             f"voice notes ({timing['where']})" if timing else "not run"),
                "status": ("met" if timing and timing["seconds"] <= 60 else "not met") if timing else "not run"})
    out.append({"target": "Voice check on team's own voices and clones: report", "measured": "not run",
                "status": "not run (no consented recordings collected)"})
    return out


def claims_ids() -> set[str]:
    return set(re.findall(r"^\| (C-\d+) \|", (ROOT / "CLAIMS.md").read_text(encoding="utf-8"), re.M))


def build() -> dict:
    known = claims_ids()
    rows = []
    for page, promise, status, ids, note in PROMISES:
        missing = [i for i in ids if i not in known]
        rows.append({"deck": page, "promise": promise, "status": status, "claims": ids, "missing_claims": missing,
                     "note": note})
    return {"promises": rows, "targets": targets(),
            "counts": {s: sum(r["status"] == s for r in rows) for s in ("built", "partial", "cut deliberately", "not built")}}


def markdown(d: dict) -> str:
    L = ["# Plan versus delivered", "",
         "Generated by `python scripts/plan_vs_delivered.py` from the Round 1 deck's promises and CLAIMS.md. "
         f"Built: {d['counts']['built']} · partial: {d['counts']['partial']} · cut deliberately: "
         f"{d['counts']['cut deliberately']} · not built: {d['counts']['not built']}.", "",
         "| Deck | Promise | Status | Proof (CLAIMS.md) | Note |", "|---|---|---|---|---|"]
    for r in d["promises"]:
        L.append(f"| {r['deck']} | {r['promise']} | **{r['status']}** | {', '.join(r['claims']) or '-'} | {r['note']} |")
    L += ["", "## The deck's four finale targets (p8: \"targets, not results\")", "",
          "| Target | Measured | Status |", "|---|---|---|"]
    L += [f"| {t['target']} | {t['measured']} | {t['status']} |" for t in d["targets"]]
    return "\n".join(L) + "\n"


def main() -> int:
    d = build()
    bad = [r for r in d["promises"] if r["missing_claims"]]
    (ROOT / "PLAN_VS_DELIVERED.md").write_text(markdown(d), encoding="utf-8")
    print(markdown(d))
    if bad:
        print("ERROR: promises point at missing claims:", [(r["promise"], r["missing_claims"]) for r in bad])
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
