#!/usr/bin/env python3
"""FINALE_SLIDE.md is generated from CLAIMS.md so the slide matches the claims line for line (hard rule 4).

    python scripts/make_slide.py           -> FINALE_SLIDE.md      (acceptance.py checks it is up to date)
"""
from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def build() -> str:
    rows = []
    for line in (ROOT / "CLAIMS.md").read_text(encoding="utf-8").splitlines():
        m = re.match(r"^\| (C-\d+) \| (.*?) \| (.*?) \| (.*?) \| (.*?) \| (.*?) \|$", line)
        if m:
            rows.append(m.groups())
    rows.sort(key=lambda r: int(r[0][2:]))
    runs = [r for r in rows if r[4].startswith("runs")]
    other = [r for r in rows if not r[4].startswith("runs")]
    L = ["# Finale slide: what VERIQ does (generated from CLAIMS.md by scripts/make_slide.py; do not edit by hand)", "",
         "Say every line exactly as written. Each one runs today; the proof command is in CLAIMS.md.", "",
         "| # | What VERIQ does | Data / status |", "|---|---|---|"]
    L += [f"| {r[0]} | {r[1]} | {r[4]} |" for r in runs]
    L += ["", "**Not run yet (say so if asked):** " + ("; ".join(f"{r[0]} {r[1]}" for r in other) or "none"), "",
          "Data: chats are synthetic (generated by us) or written blind by teammates; voice data is public (ASVspoof "
          "2019 LA, FSDD) or synthetic (Kokoro TTS). No real victims' data. Claude (Anthropic) was used to write code "
          "and documents. No partnership with I4C, SEBI, RBI, NPCI or any bank is claimed. VERIQ can be fooled: see "
          "the evasion lab.", ""]
    return "\n".join(L)


def main() -> int:
    (ROOT / "FINALE_SLIDE.md").write_text(build(), encoding="utf-8")
    print(build())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
