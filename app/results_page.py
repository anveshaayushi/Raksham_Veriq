from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def _load(rel: str):
    p = ROOT / rel
    try:
        return json.loads(p.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None


def chat_rows():
    r = _load("bench/results_test.json")
    if not r:
        return None
    return {"chats": r["chats"], "payees": r["payees"], "extraction": r["extraction"],
            "decision_accuracy": r["decision_accuracy"], "false_alarms": r["false_alarms_on_legit_payees"],
            "missed_scams": r["scam_payees_marked_no_major_issue"], "ms": r["ms_per_chat"],
            "failures": r.get("failures", [])[:5], "failure_count": r.get("failure_count", 0)}


def voice_rows():
    r = _load("bench/voice/results.json")
    if not r:
        return None
    d = r["detectors"]
    return {"n": r["n"], "seconds_per_clip": r["seconds_per_clip_cpu"], "pre": d["pretrained"], "head": d["trained_head"],
            "model_version": r.get("exported", {}).get("model_version", "")}


def adversarial():
    return _load("bench/results_adversarial.json")


def cross_dataset_rows():
    """ASVspoof 2019 LA eval: pretrained AASIST (B's run) and our head (C's run), recomputed from the committed CSVs."""
    import csv
    import importlib.util
    spec = importlib.util.spec_from_file_location("mrr", ROOT / "scripts" / "make_results_rows.py")
    if spec is None or not (ROOT / "scripts" / "make_results_rows.py").is_file():
        return None
    mrr = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mrr)
    out = []
    for name, rel, pol in (("Pretrained AASIST (in-distribution: trained on this dataset)", "results/asvspoof/asv_eval.csv",
                            "higher_is_real"),
                           ("Our trained head (never saw this dataset)", "results/asvspoof/head_v1_eval.csv", "higher_is_fake")):
        p = ROOT / rel
        if not p.is_file():
            continue
        rows = list(csv.DictReader(open(p, encoding="utf-8")))
        b = mrr.block(rows, pol)
        out.append({"model": name, "n": f"{b['n_real']}/{b['n_fake']}", "AUC": round(b["auc"], 3),
                    "EER": round(b["eer"], 3), "genuine flagged": f"{b['fa']:.1%} [{b['fa_ci'][0]:.3f}, {b['fa_ci'][1]:.3f}]",
                    "synthetic missed": f"{b['miss']:.1%} [{b['miss_ci'][0]:.3f}, {b['miss_ci'][1]:.3f}]"})
    return out or None


def names_eval():
    return _load("bench/names/results.json")


def render(st, md_escape) -> None:
    st.header("How accurate is VERIQ?")
    st.caption("Every number here comes from a command in this repository, run on data the system never trained on. "
               "All data is synthetic or public. Small sets: read the intervals and the failure cases.")
    c = chat_rows()
    blind = _load("bench/results_test_blind_24oct.json")
    st.subheader("1 · Chat and payee checks (rules)")
    if c:
        st.markdown(
            f"- **{c['chats']} chats in the held-out synthetic test (generated by us), {c['payees']} payees** (`python -m bench.run test`)\n"
            f"- Payees found: **{c['extraction']['tp']}/{c['payees']}**, false pickups: **{c['extraction']['fp']}** "
            "(decoys: e-mails, phone and order numbers, URLs)\n"
            f"- Answers as expected: **{c['decision_accuracy'] * 100:.1f}%**"
            + (f" (first blind run on 24 Oct: **{blind['decision_accuracy'] * 100:.1f}%**; the shop-name fix that closed "
               "the gap was made after seeing those failures, so only the blind number counts as unseen)\n"
               if blind and blind["decision_accuracy"] != c["decision_accuracy"] else "\n") +
            f"- False alarms on genuine payees: **{c['false_alarms']['count']}/{c['false_alarms']['of']}** · "
            f"scams marked 'no major issue': **{c['missed_scams']['count']}/{c['missed_scams']['of']}**\n"
            f"- Time per chat (rules only): median {c['ms']['median']} ms")
        if not c["failures"] and blind and blind.get("failures"):
            from collections import Counter
            kinds = Counter(f"{f.get('typed_name')} → {f['got']} (expected {f['expected']})" for f in blind["failures"])
            st.markdown(f"**Failure cases in the blind run ({blind.get('failure_count')}, fixed since):** " + "; ".join(
                md_escape(f"{k} ×{n}") for k, n in kinds.most_common(3)))
        if c["failures"]:
            from collections import Counter
            kinds = Counter(f"{f.get('typed_name')} → {f['got']} (expected {f['expected']})" for f in c["failures"])
            st.markdown(f"**Failure cases ({c['failure_count']}):** " + "; ".join(
                md_escape(f"{k} ×{n}") for k, n in kinds.most_common(3)))
    else:
        st.info("Not run yet: `python -m bench.run test`.")
    v = voice_rows()
    st.subheader("2 · Voice-note check (AASIST + our trained head)")
    if v:
        pre, head = v["pre"], v["head"]
        st.markdown(
            f"Held-out test: {v['n']['test_en']} English clips (2 real speakers, 8 synthetic voices never seen in "
            f"training) + {v['n']['test_hindi_fake_only']} Hindi synthetic clips; WhatsApp-like Opus compression; "
            "same preprocessing as the app. Threshold fixed on a separate dev set (target: ≤5% genuine flagged).")
        st.table({
            "": ["AUC", "Equal error rate", "Genuine clips flagged (95% CI)", "Synthetic clips caught (95% CI)",
                 "Hindi synthetic caught"],
            "Pretrained AASIST": [str(pre["test_auc"]), str(pre["test_eer"]),
                                  f"{pre['test_genuine_flagged']:.1%} {pre['test_genuine_flagged_95ci']}",
                                  f"{pre['test_synthetic_caught']:.1%} {pre['test_synthetic_caught_95ci']}",
                                  f"{pre['hindi_synthetic_caught']:.1%}"],
            "AASIST + our trained head": [str(head["test_auc"]), str(head["test_eer"]),
                                          f"{head['test_genuine_flagged']:.1%} {head['test_genuine_flagged_95ci']}",
                                          f"{head['test_synthetic_caught']:.1%} {head['test_synthetic_caught_95ci']}",
                                          f"{head['hindi_synthetic_caught']:.1%}"]})
        st.markdown("**What this means:** training helped, but about 1 in 5 genuine clips is still flagged. So a voice "
                    "flag only asks for a human review; it never accuses or clears a payee. The payee-name check decides.")
        st.markdown("**Known failures:** some speakers are flagged often; one synthetic voice is rarely caught; a second "
                    "compression pass lowers the catch rate; only one TTS engine and digit strings were tested; real "
                    "voice clones were not tested.")
    else:
        st.info("Not run yet: `python -m bench.voice.train_eval`.")
    x = cross_dataset_rows()
    st.subheader("2b · Voice on a public benchmark: ASVspoof 2019 LA (held-out eval split)")
    if x:
        st.table({k: [r[k] for r in x] for k in x[0]})
        st.markdown("**What this means:** on held-out clips of the dataset AASIST was trained on (so close to its "
                    "training data), it still misses about half of the synthetic clips at the threshold fitted on LA dev, "
                    "and abstains on 9.5% (57 of 600: too little speech). In-the-Wild and other datasets: **not run**. "
                    "Our own head, which looked good in-domain (AUC 0.82), falls to chance here and is **switched off by "
                    "default**. The app uses pretrained AASIST with that LA-dev threshold only as a **weak review cue**: a "
                    "flag asks a person to review; 'no signal' never clears or reassures. Named failure: our synthetic demo "
                    "clip (Kokoro TTS) is NOT flagged.")
        st.caption("Contains information from ASVspoof 2019 (https://doi.org/10.7488/ds/2555), made available under the "
                   "ODC Attribution License. 100 genuine + 100 synthetic clips, each also as mp3 and Opus.")
    else:
        st.info("Not run in this copy (results/asvspoof/ missing).")
    n = names_eval()
    if n:
        fd, dd = n["false_discrepancy_on_same_entity"], n["discrepancy_found_on_unrelated_business"]
        st.subheader("2c · Name matcher on 97 labelled name pairs")
        st.markdown(f"- Same firm, wrongly called a mismatch: **{fd['count']}/{fd['of']}** (95% CI {fd['wilson95']})\n"
                    f"- Unrelated businesses caught: **{dd['count']}/{dd['of']}** · a non-firm name called a match: "
                    f"**{n['dangerous_match_on_not_same']}**\n"
                    "- Written by the team after the matcher (a specification check, not a blind test). Misses: "
                    + "; ".join(md_escape(f"{e['claimed_firm']} vs {e['shown_name']} -> {e['verdict']}")
                                for e in n["errors"] if e["verdict"] == "discrepancy"))
    a = adversarial()
    st.subheader("3 · Red-team: attacks we tried")
    if a:
        st.markdown(f"Defended attacks passed: **{a['defended_attacks_passed']}/{a['defended_attacks']}** · "
                    f"known gaps still open: **{a['known_gaps_still_failing']}/{a['known_gaps']}** "
                    "(`python -m bench.adversarial`)")
        st.table({"Attack": [r["attack"] for r in a["rows"]], "Expected": [r["expected"] for r in a["rows"]],
                  "Got": [r["got"] for r in a["rows"]],
                  "Result": ["pass" if r["pass"] else ("KNOWN GAP" if r["known_gap"] else "FAIL") for r in a["rows"]]})
    st.subheader("4 · Evasion lab: try to fool it yourself")
    st.write("Type a message a scammer might send. VERIQ shows which pressure cues it finds, before and after undoing "
             "common disguises (leetspeak, spaced or dotted letters).")
    txt = st.text_input("A scam-style sentence", "P.a.y 18% t@x to w1thdraw, u_r_g_e_n_t", key="evade_text")
    if txt:
        from extract import CUE_RX, deobfuscate
        raw = sorted({t for t, rx in CUE_RX if rx.search(txt)})
        dob = sorted({t for t, rx in CUE_RX if rx.search(deobfuscate(txt))} - set(raw))
        st.markdown(f"Found as written: **{', '.join(raw) or 'nothing'}** · found after undoing disguises: "
                    f"**{', '.join(dob) or 'nothing more'}**")
    c1, c2 = st.columns(2)
    claimed = c1.text_input("Firm the chat claims", "Navyug Broking Pvt Ltd", key="evade_firm")
    shown = c2.text_input("Name the bank app shows", "NAVYUG ONLINE TRADERS", key="evade_shown")
    if claimed and shown:
        from match import match_names
        v, why = match_names(claimed, shown)
        st.markdown(f"Name check: **{v}** ({md_escape(why)})")
    st.markdown("**Known ways to fool VERIQ today** (from the red-team table): a mule account opened in the firm's exact "
                "name; pressure written without any keyword (\"your chance closes soon\"); voice clones from engines "
                "we have not tested; a scam with no payment destination in the chat (payment link sent elsewhere).  \n"
                "**What we would change next:** a semantic pressure classifier trained on labelled Indian scam chats "
                "(with consent), payee-name checks from the bank itself instead of user-typed names, a voice detector "
                "trained on many TTS engines and Indian languages with a threshold set per channel, and OCR for "
                "screenshots without a QR code.")
    st.caption("Limits: synthetic data written or generated by the team; not real victims' chats or real voice clones.")
